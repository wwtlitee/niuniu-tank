'use strict';
// Reuse the actual model factories, without booting either source game's runtime.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
function source(file){return fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n');}
function section(text,start,end){const a=text.indexOf(start),b=text.indexOf(end,a+start.length);if(a<0||b<0)throw Error('Model source boundary changed: '+start);return text.slice(a,b).trim();}
const engine=source('js/engine.js'),classic=source('js/classic/classic-engine.js'),hero=source('js/hero-models.js');
const factories=[
 section(classic,'  function makeTank(','  function tileColor(').replace('function makeTank(','function classicTank('),
 section(engine,'function mergeDirectMeshesByMaterial(','function makeTank('),
 section(engine,'function makeTank(','/* 生存模式批量部队'),
 section(engine,'function makeRtsTank(','/* ---------------- 实体'),
 section(hero,'function heroModelKit(','function makeHeroHubModel(')
].join('\n\n');
const header=`/* Generated by tools/generate-racing-legacy.cjs; source model factories, Unclecow.
 * Source digest: ${crypto.createHash('sha256').update(factories).digest('hex')}
 * Visual-only adapter: no source game state or combat modules are loaded.
 */
(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory;else root.RacingLegacyModels=factory(root.THREE,root.RacingModels);})(typeof window==='object'?window:globalThis,function(T,M){
 'use strict';
 // Refine hard box edges locally; do not alter THREE or the source modes.
 const THREE={...T,BoxGeometry:class {constructor(w,h,d){return M.bevelBox(w,h,d,Math.min(.045,w/8,h/8,d/8));}}};
 const chamferedBox=(w,h,d)=>M.bevelBox(w,h,d,.055);
 const ACTIVE_MODE={key:'survival'},SurvivalSystem={FRIENDLY_UNIT_TYPES:{hero:{scale:1}}};
 const warmEmissiveMaterial=color=>new T.MeshStandardMaterial({color});
`;
fs.writeFileSync(path.join(root,'js/racing/racing-legacy-models.js'),header+factories+'\n'+source('tools/racing-legacy-adapter.txt'),'utf8');
console.log('Generated racing legacy model factories');
